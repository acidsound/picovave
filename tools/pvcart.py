"""The built-in default cart, and the C array the three builds bake from it.

picovave runs .p8.png carts (src/picovave_cart.h), so there is no .p8 text parser in the
build either: the default cart - what the panel shows when the store holds no cart - is
assembled here as the COOKED cart a .p8.png carries.

    [0, 17152)       cartridge ROM (gfx, map, sprite flags, music, sfx)
    [17152, 32800)   code section

The surround cart is the panel's button test: it sweeps a pixel along a row and lights one
per button held (btn) or newly pressed (btnp). It draws with cls()/pset() only, so its
cartridge ROM is zero, and its code section is the RAW form (no ':c:'/PXA header) - the
pre-0.1.7 layout, which the device's expander copies verbatim. That is why the default cart
needs no compressor: only a .p8.png that PICO-8 itself saved carries a compressed section,
and the device's decoder handles those (femto8/src/lexaloffle).

Kept in step with web/sim/p8png.mjs (the same cart, made in JS for the page tests) and with
femto8/src/p8_emu.h's COOKED_SIZE (p8_load_cooked re-checks the size before it runs).
"""

COOKED_SIZE = 160 * 205            # 32,800: the pixels of a .p8.png, one byte each
CART_ROM_SIZE = 0x4300             # 17,152: ROM, then the code section
CODE_SIZE = COOKED_SIZE - CART_ROM_SIZE
CODE_RAW_MAX = 0x3d00              # 15,616: what a raw code section holds

# The panel's button test. Tabs, as PICO-8's own editor writes them.
DEFAULT_SCRIPT = """function _init()
\tcls()
\tx = 0
end 

function _update()

end 

function _draw()

\tpset (x-1, 8, 0)
\tpset (x, 8, 7)

\tfor n=0,5 do
 \tif (btn(n))\tpset (x, 16 + n * 2, 7)
 \tif (btnp(n))\tpset (x,16 + n * 2, 8)
\tend
\t
\tx+=1
\tif (x > 127) then 
\t\tx = 0
\t\tcls()
\tend

end 
"""


def cooked(script=DEFAULT_SCRIPT, rom=None):
    """A cooked cart: `rom` (CART_ROM_SIZE bytes, zero if None) then a RAW code section."""
    if rom is not None and len(rom) != CART_ROM_SIZE:
        raise ValueError("cartridge ROM is %d B, not %d" % (len(rom), CART_ROM_SIZE))
    code = script.encode("ascii")
    if len(code) > CODE_RAW_MAX:
        raise ValueError("raw code section is %d B, over %d" % (len(code), CODE_RAW_MAX))
    return (bytes(rom) if rom is not None else bytes(CART_ROM_SIZE)) + code \
        + bytes(CODE_SIZE - len(code))


def header(origin="tools/pvcart.py", script=DEFAULT_SCRIPT):
    """The C source the builds compile: cart_default[] and cart_default_len, the BOOT cart.

    A bare cooked cart - no wire magic: this one never came over SysEx, so a target hands it
    to p8_load_cooked() as it is (see hh_cart_data in src/picovave.c and sim/sim.c)."""
    data = cooked(script)
    lines = ["/* generated by %s - do not edit */" % origin,
             "#pragma once", "#include <stdint.h>", "",
             "static const uint8_t cart_default[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + " ".join("%d," % b for b in data[i:i + 16]))
    lines += ["};", "enum { cart_default_len = %d };" % len(data)]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "header":
        sys.stdout.write(header())
    else:
        data = cooked()
        print("cart_default  %d B (ROM %d + code %d, raw)" % (len(data), CART_ROM_SIZE, CODE_SIZE))
