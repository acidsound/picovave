/* preview.c - a third consumer of the firmware's shared code, for the host.
 *
 * It compiles the firmware's own app layer (src/picovave_p8.h) and the vendored femto8
 * engine exactly as the ROM and the browser simulator do, with only the hh_* HAL swapped:
 * the panel push is captured into a buffer instead of driven over SPI1, and the inputs
 * come from a small script instead of SPI2. Its screen must be byte-identical to the
 * simulator's, which is what tools/verify_final.py asserts - idle and, with a script,
 * for the same sequence of presses. That equality is the evidence that the browser (and
 * so the host) shows the ROM's pixels.
 *
 *   python3 tools/preview_picovave.py -> build/picovave/preview.ppm + .txt
 *
 * Script (optional third argument), one event per line:
 *     btn 5 1      button 5 down        btn 5 0   up
 *     key 24 1     key 24 down          key 24 0  up
 *     enc 3 2      encoder 3, +2 detents          enc 3 -1  backwards
 *     pad 5 110    pad 5 hit, velocity 110        pad 5 0   release
 *     fad 2 100    fader 2 -> 100 (0..127)
 *     whl 0 600    wheel 0 (pitch) -> raw 600 (0..1023)
 * Each event is applied and then one frame runs (picovave_frame()), which is exactly
 * what the page does per sim_frame() call when it walks the same script.
 */
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

#include "cart_default.h"        /* generated by tools/preview_picovave.py: cart_default[] */
#include "gdi.h"                 /* the display seam: GDI_W/GDI_OUT_W and gdi_expand_row() */
#include "../src/picovave_input.h"     /* hin_t / HIN_*: the HAL below is written in its terms */

/* The capture: what the panel will show, in the engine's native RGB565. seam_host.c expands the
 * engine's 128x128 screen into p8_panel_fb (gdi.h) - the same gdi_expand_row() the board blits
 * row by row - and the wasm's sim_fb() holds the same numbers, so the two PPMs are comparable
 * directly. */
static uint16_t cap[240 * 240];
static uint32_t cap_pushes, cap_bytes;

/* ---- the hh_* HAL the shared app expects ---- */
static uint32_t pv_btn;
static uint64_t pv_key;
static int8_t   pv_enc[HIN_NENC];
static uint16_t pv_pad;
static uint8_t  pv_pad_vel[HIN_NPAD];
static uint8_t  pv_fader[HIN_NFADER];
static uint16_t pv_wheel[HIN_NWHEEL];

static void hh_time_init(void) { }

/* femto8/seam/seam_host.c: the engine's 128x128 screen, the 240x240 it is expanded into, and the
 * counts seam_host.c keeps for the same push the board does. */
extern uint16_t p8_screen_fb[GDI_W * GDI_H];
extern uint16_t p8_panel_fb[GDI_OUT_W * GDI_OUT_H];
extern uint32_t p8_panel_draws;
extern uint32_t p8_panel_bytes;

static void hh_lcd_init(void) { p8_panel_draws = p8_panel_bytes = 0; }

static void hh_input_init(void)
{
    uint32_t i;
    pv_btn = 0;
    pv_key = 0;
    for (i = 0; i < HIN_NENC; i++)
        pv_enc[i] = 0;
    pv_pad = 0;
    for (i = 0; i < HIN_NPAD; i++)
        pv_pad_vel[i] = 0;
    for (i = 0; i < HIN_NFADER; i++)
        pv_fader[i] = 0;
    for (i = 0; i < HIN_NWHEEL; i++)
        pv_wheel[i] = 0;
}

static void hh_input_read(hin_t *in)
{
    uint32_t i;
    in->buttons = pv_btn;
    in->keys = pv_key;
    for (i = 0; i < HIN_NENC; i++) {
        in->enc[i] = pv_enc[i];
        pv_enc[i] = 0;
    }
    in->pads = pv_pad;
    for (i = 0; i < HIN_NPAD; i++)
        in->pad_vel[i] = pv_pad_vel[i];
    for (i = 0; i < HIN_NFADER; i++)
        in->fader[i] = pv_fader[i];
    for (i = 0; i < HIN_NWHEEL; i++)
        in->wheel[i] = pv_wheel[i];
}

/* The cart: a host preview has no flash store, so it always runs the baked cart - the same
 * one tools/build_sim.py bakes into the wasm, and the same one a blank device carries. */
static const uint8_t *hh_cart_data(void) { return cart_default; }
static uint32_t hh_cart_size(void) { return (uint32_t)cart_default_len; }
static int hh_cart_kind(void) { return 0; }        /* the preview runs the baked cooked cart */
static int hh_cart_next(void) { return 0; }        /* one cart here: there is no next candidate */
static void hh_boot_stage(int stage) { (void)stage; }  /* no panel in a host preview */

#include "../src/picovave_p8.h"

/* The shared drawing core, exactly as the firmware compiles it: the crash screen is the same
 * function the ROM's fault handler calls, so `preview --crash` renders the real layout from a
 * scripted record instead of waiting for a device to die. hg_fb is the engine's own screen
 * surface, as on the device - the 128x128 in gdi.h, not a 240x240 canvas. */
#include "../src/picovave_font.h"
#define hg_fb p8_screen_fb
#include "../src/picovave_gfx.h"

/* The panel push (gdi_display_update_async) is seam_host.c's, so the expansion is the same code
 * the board runs - and the capture below is that function's output. */
static void capture(void)
{
    cap_pushes = p8_panel_draws;
    cap_bytes = p8_panel_bytes;
    memcpy(cap, p8_panel_fb, sizeof cap);
}

static void apply(const char *kind, int id, int v)
{
    if (kind[0] == 'b' && id >= 0 && id < (int)HIN_NBTN) {          /* btn */
        if (v)
            pv_btn |= 1u << id;
        else
            pv_btn &= ~(1u << id);
    } else if (kind[0] == 'k' && id >= 0 && id < (int)HIN_NKEY) {   /* key */
        if (v)
            pv_key |= (uint64_t)1u << id;
        else
            pv_key &= ~((uint64_t)1u << id);
    } else if (kind[0] == 'e' && id >= 0 && id < (int)HIN_NENC) {   /* enc */
        pv_enc[id] = (int8_t)(pv_enc[id] + v);
    } else if (kind[0] == 'p' && id >= 0 && id < (int)HIN_NPAD) {   /* pad */
        if (v) {
            pv_pad |= (uint16_t)(1u << id);
            pv_pad_vel[id] = (uint8_t)(v > 127 ? 127 : v);
        } else {
            pv_pad &= (uint16_t)~(1u << id);
            pv_pad_vel[id] = 0;
        }
    } else if (kind[0] == 'f' && id >= 0 && id < (int)HIN_NFADER) { /* fader */
        pv_fader[id] = (uint8_t)(v < 0 ? 0 : v > 127 ? 127 : v);
    } else if (kind[0] == 'w' && id >= 0 && id < (int)HIN_NWHEEL) { /* wheel */
        pv_wheel[id] = (uint16_t)(v < 0 ? 0 : v > 1023 ? 1023 : v);
    }
}

static void run_script(const char *path)
{
    FILE *f = fopen(path, "r");
    char line[128], kind[16];
    int id, v;
    if (!f) {
        perror(path);
        return;
    }
    while (fgets(line, sizeof line, f)) {
        if (line[0] == '#' || line[0] == '\n' || line[0] == '\r')
            continue;
        if (sscanf(line, "%15s %d %d", kind, &id, &v) != 3)
            continue;
        apply(kind, id, v);
        picovave_frame();                  /* one frame, exactly as the page would run it */
    }
    fclose(f);
}

static int write_ppm(const char *path)
{
    FILE *f = fopen(path, "wb");
    uint32_t i;
    if (!f) { perror(path); return 1; }
    fprintf(f, "P6\n%d %d\n255\n", 240, 240);
    for (i = 0; i < 240u * 240u; i++) {
        uint16_t c = cap[i];
        uint8_t out[3] = {(uint8_t)(((c >> 11) & 31u) << 3 | ((c >> 11) & 31u) >> 2),
                          (uint8_t)(((c >> 5) & 63u) << 2 | ((c >> 5) & 63u) >> 4),
                          (uint8_t)((c & 31u) << 3 | (c & 31u) >> 2)};
        fwrite(out, 1, 3, f);
    }
    fclose(f);
    printf("preview %s\n", path);
    return 0;
}

static int write_ascii(const char *path)
{
    FILE *f = fopen(path, "w");
    uint32_t x, y;
    if (!f) { perror(path); return 1; }
    for (y = 0; y < 240u; y += 4) {
        for (x = 0; x < 240u; x += 2)
            fputc(cap[y * 240u + x] ? (cap[y * 240u + x] & 0xFF00u ? '#' : '.') : ' ', f);
        fputc('\n', f);
    }
    fclose(f);
    printf("ascii   %s\n", path);
    return 0;
}

/* the pathological record: a store off the bottom of the user stack (sp BELOW stack_lo) with
 * the high-water mark pinned at the whole stack - what fm1_fault would have found if a cart
 * recursed until the guard tripped. */
static void show_crash(int boot_report)
{
    hg_crash_t h;
    memset(&h, 0, sizeof h);
    h.pc = 0x0201E944u;               /* [sp+32] = r1, inside setjmp's prologue */
    h.vec = 1u;                       /* the CPU-exception entry */
    h.emu = 8u;                       /* EMU_MSG bit 3: sp outside the stack window */
    h.dbg = 0u;
    h.sp = 0x01C73F80u;
    h.rets = 0x02002BC2u;
    h.etm0 = 0x0201E932u;
    h.etm1 = 0x02012ACAu;
    h.stack_lo = 0x01C74100u;
    h.stack_top = 0x01C7A000u;
    h.stack_used = 0x5F00u;
    h.count = 3u;
    h.early = 3u;
    h.uptime_ms = 1520u;
    h.boot_report = (uint32_t)boot_report;   /* the wider headline has to fit too */
    hg_crash_screen(&h);
    gdi_display_update_async(0, 0);   /* the same expand+push path the frames take */
}

int main(int argc, char **argv)
{
    if (argc > 1 && (strcmp(argv[1], "--crash") == 0 || strcmp(argv[1], "--crash-boot") == 0)) {
        show_crash(strcmp(argv[1], "--crash-boot") == 0);    /* --crash-boot: the report the next boot draws */
        capture();
        return write_ppm(argc > 2 ? argv[2] : "build/picovave/crash.ppm");
    }
    hh_time_init();
    picovave_boot();                     /* one frame; its screen is the idle screen */
    if (argc > 3)
        run_script(argv[3]);
    capture();

    printf("host    pushes=%u bytes=%u boots=%u status=%d\n",
           cap_pushes, cap_bytes, picovave_boots, picovave_status);
    if (write_ppm(argc > 1 ? argv[1] : "build/picovave/preview.ppm")) return 1;
    if (argc > 2 && write_ascii(argv[2])) return 1;
    return 0;
}
