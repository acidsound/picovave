#include "../src/picovave_p8.h"

#include "cart_default.h"        /* generated by tools/build_sim.py: cart_default[] */

/* ---- the cart store --------------------------------------------------------
 * The device keeps carts in flash (the SLOOP store, picovave_cart.h); here the same layout lives
 * in a RAM array, so the slot geometry, the CRC and the protocol are the firmware's, byte for
 * byte. The array is not touched by sim_init(): a POWER-ON re-reads the store, as the flash
 * survives a reboot. */
static uint8_t sim_store[PV_STORE_SIZE];

int hh_store_read(uint32_t off, void *dst, uint32_t n)
{
    if (off + n > PV_STORE_SIZE) return -1;
    memcpy(dst, sim_store + off, n);
    return 0;
}
int hh_store_erase(uint32_t off, uint32_t n)
{
    if (off + n > PV_STORE_SIZE) return -1;
    memset(sim_store + off, 0xFF, n);    /* NOR reads back 1s; a 0xFF header is no cart */
    return 0;
}
int hh_store_write(uint32_t off, const void *src, uint32_t n)
{
    if (off + n > PV_STORE_SIZE) return -1;
    memcpy(sim_store + off, src, n);
    return 0;
}

/* The reply path: the page and the Node test read the last F0..F7 frame the device sent back.
 * LIST answers with one INFO frame per slot and then an OK, so the last INFO is kept too. */
static uint8_t  sim_reply_buf[80];
static uint32_t sim_reply_n;
static uint8_t  sim_info_buf[80];
static uint32_t sim_info_n;
void hh_cart_reply(const uint8_t *msg, uint32_t n)
{
    if (n > sizeof sim_reply_buf) n = sizeof sim_reply_buf;
    memcpy(sim_reply_buf, msg, n);
    sim_reply_n = n;
    if (n >= 7 && msg[5] == 0x12) {
        memcpy(sim_info_buf, msg, n);
        sim_info_n = n;
    }
}

/* ---- the cart this build runs: the active slot, else the baked default ------ */
/* The cooked cart to run: the active slot's payload PAST its 4-byte wire magic (pv_hdr_read has
 * checked the magic and the length), or the baked default cart, which was never on the wire and
 * so is a bare cooked cart. p8_load_cooked() checks the size. */
const uint8_t *hh_cart_data(void)
{
    if (pv_run_slot >= 0)
        return sim_store + PV_SLOT_BASE((uint8_t)pv_run_slot) + PV_SLOT_DATA + PV_COOKED_MAGIC_LEN;
    return cart_default;
}
uint32_t hh_cart_size(void)
{
    if (pv_run_slot < 0)
        return (uint32_t)cart_default_len;
    return pv_cart.slot_len[(uint8_t)pv_run_slot] - PV_COOKED_MAGIC_LEN;
}
int hh_cart_kind(void)
{
    return pv_run_slot >= 0 ? (int)pv_cart.slot_kind[(uint8_t)pv_run_slot] : 0;
}
int hh_cart_next(void) { return pv_run_next(); }
void hh_boot_stage(int stage) { (void)stage; }   /* no panel here; the page shows its own status */

