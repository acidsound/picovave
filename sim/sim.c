/* sim.c - picovave in a browser: the PICO-8 app, compiled to WebAssembly.
 *
 * It includes the firmware's own app layer (../src/picovave_p8.h) unchanged and swaps
 * only the HAL (picovave_sim_hal.h) - so the screen comes from the ROM's code. The
 * engine underneath is the vendored femto8 (../femto8/); its platform seam for wasm
 * is ../femto8/seam/seam_sim.c.
 *
 * Exports for the page (see web/sim/index.html) and the worklet:
 *   sim_init, sim_frame, sim_fb, sim_draws, sim_ms, sim_bytes, sim_boots, sim_wdt,
 *   sim_button, sim_key, sim_enc, sim_pad, sim_fader, sim_wheel, sim_midi,
 *   sim_rate, sim_render, sim_out_l, sim_out_r, sim_pads, sim_leds,
 *   sim_sysex_in, sim_sysex, sim_cart_active, sim_cart_replies, sim_cart_reply,
 *   sim_reply, sim_reply_len, sim_heap_peak, sim_heap_used (sim/device_alloc.c - the device's own
 *   allocator; sim/heap_probe.c's cost model with --probe-alloc).
 *
 * The cart store and the SysEx upload protocol are the firmware's own too: sim.c implements the
 * device's three store operations over a RAM array and includes ../src/picovave_cart.h, so the
 * page can upload a .p8 over the same BEGIN/DATA/END protocol the device will speak.
 *
 * The inputs write the same logical state the firmware reads from its matrix + ADC
 * HAL, so picovave_p8.h cannot tell them apart. PICO-8 audio is rendered here with the
 * engine's own render_sounds(), on the page's audio clock. */
#include <stdint.h>
#include <string.h>

#define HG_W 240
#define HG_H 240
#include "../src/picovave_input.h"
#include "picovave_sim_hal.h"
